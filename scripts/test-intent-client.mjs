import assert from 'node:assert/strict';
const values = new Map();
globalThis.localStorage = { getItem: k => values.get(k) ?? null, setItem: (k,v) => values.set(k,v) };
Object.defineProperty(globalThis, 'navigator', { value: { doNotTrack: '0', globalPrivacyControl: false }, configurable: true });
globalThis.window = { dataLayer: [] };
globalThis.location = { pathname: '/reviews', origin: 'https://example.com', href: 'https://example.com/reviews?email=private@example.com' };
const events = new EventTarget();
globalThis.document = Object.assign(events, { querySelector: () => ({}), visibilityState: 'visible', hasFocus: () => false });
const { trackIntent, readIntent } = await import('../src/scripts/intent-tracking.ts');
trackIntent('calculator_start'); trackIntent('calculator_start'); trackIntent('calculator_result'); trackIntent('email_address');
assert.equal(readIntent().counts.calculator_start, 1);
assert.equal(window.dataLayer.filter(e=>e.cv_event_name==='calculator_start').length, 1);
assert.ok(!JSON.stringify(window.dataLayer).includes('private@example.com'));
assert.ok(!JSON.stringify(window.dataLayer).includes('clearview:vid'));
const size = window.dataLayer.length;
navigator.doNotTrack = '1'; trackIntent('phone_interest'); assert.equal(readIntent(), null);
navigator.doNotTrack = '0'; navigator.globalPrivacyControl = true; trackIntent('phone_interest'); assert.equal(readIntent(), null);
assert.equal(window.dataLayer.length, size);
document.dispatchEvent(new Event('astro:before-swap'));
console.log('PASS: client counters deduplicate actions, exclude arbitrary fields and query values, and suppress events under DNT/GPC.');
